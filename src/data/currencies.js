export function currencyOf(country) {
  return COUNTRY_CURRENCIES[country] ?? DEFAULT_CURRENCY
}

export function currencyAfterCountryChange(
  previousCountry,
  nextCountry,
  currency,
) {
  if (currency !== currencyOf(previousCountry)) return currency
  return currencyOf(nextCountry)
}
